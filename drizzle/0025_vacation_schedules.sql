CREATE TABLE `vacation_schedules` (
  `id` int NOT NULL AUTO_INCREMENT,
  `companyId` int NOT NULL,
  `memberAccountId` int NOT NULL,
  `startDate` date NOT NULL,
  `endDate` date NOT NULL,
  `days` int NOT NULL,
  `status` enum('scheduled','cancelled') NOT NULL DEFAULT 'scheduled',
  `notes` text,
  `createdByMemberAccountId` int NOT NULL,
  `updatedByMemberAccountId` int,
  `cancelledByMemberAccountId` int,
  `cancelledAt` timestamp,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `vacation_schedules_company_member_idx` (`companyId`,`memberAccountId`),
  KEY `vacation_schedules_company_dates_idx` (`companyId`,`startDate`,`endDate`),
  KEY `vacation_schedules_status_idx` (`status`),
  CONSTRAINT `vacation_schedules_companyId_companies_id_fk` FOREIGN KEY (`companyId`) REFERENCES `companies` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `vacation_schedules_memberAccountId_member_accounts_id_fk` FOREIGN KEY (`memberAccountId`) REFERENCES `member_accounts` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `vacation_schedules_createdBy_member_accounts_id_fk` FOREIGN KEY (`createdByMemberAccountId`) REFERENCES `member_accounts` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `vacation_schedules_updatedBy_member_accounts_id_fk` FOREIGN KEY (`updatedByMemberAccountId`) REFERENCES `member_accounts` (`id`) ON DELETE SET NULL,
  CONSTRAINT `vacation_schedules_cancelledBy_member_accounts_id_fk` FOREIGN KEY (`cancelledByMemberAccountId`) REFERENCES `member_accounts` (`id`) ON DELETE SET NULL
);
